import { createHash } from "node:crypto";
import jwt from "jsonwebtoken";
import prisma from "@root/prisma.js";
import { ApiError } from "@/utils/ApiError.js";
import STATUS_CODES from "@/utils/statusCodes.js";
import { hashPassword } from "@/utils/auth.js";
import { grantSeatQuota } from "./org.quota.js";
import { countSeatsInUse, getCurrentOrgSubscription } from "./org.service.js";

const hashToken = (token: string) => createHash("sha256").update(token).digest("hex");

/**
 * Public invite flow. Invited people always get a brand-new account created
 * here an email that already has an account can't be invited, so a personal
 * account is never merged into an org.
 */
class OrgInviteService {
  private async loadInvite(token: string) {
    const invite = await prisma.orgInvite.findUnique({
      where: { tokenHash: hashToken(token) },
      include: {
        role: { select: { name: true, isDeleted: true } },
        organization: { select: { id: true, name: true, status: true, isDeleted: true } },
      },
    });
    if (!invite || invite.revokedAt || invite.role.isDeleted || invite.organization.isDeleted) {
      throw new ApiError("This invitation isn't valid.", STATUS_CODES.NOT_FOUND);
    }
    if (invite.acceptedAt) throw new ApiError("This invitation was already used.", STATUS_CODES.CONFLICT);
    if (invite.expiresAt < new Date()) throw new ApiError("This invitation has expired.", 410);
    if (invite.organization.status !== "ACTIVE") {
      throw new ApiError("This organization isn't active.", STATUS_CODES.FORBIDDEN);
    }
    return invite;
  }

  async preview(token: string) {
    const invite = await this.loadInvite(token);
    return {
      organizationName: invite.organization.name,
      email: invite.email,
      roleName: invite.role.name,
      memberRole: invite.memberRole,
      expiresAt: invite.expiresAt,
    };
  }

  async accept(token: string, data: { firstName: string; lastName: string; password: string }) {
    const invite = await this.loadInvite(token);
    const email = invite.email.toLowerCase();

    if (await prisma.user.findUnique({ where: { email }, select: { id: true } })) {
      throw new ApiError("This email already has an account.", STATUS_CODES.CONFLICT);
    }

    const hashed = await hashPassword(data.password);

    try {
      const user = await prisma.$transaction(
        async (tx) => {
          // Re-check inside the transaction: another request may have used it.
          const fresh = await tx.orgInvite.findUnique({ where: { id: invite.id } });
          if (!fresh || fresh.acceptedAt || fresh.revokedAt) {
            throw new ApiError("This invitation was already used.", STATUS_CODES.CONFLICT);
          }

          const sub = await getCurrentOrgSubscription(tx, invite.orgId);
          // The owner may accept while billing is still being settled; everyone else needs a live plan + a free seat.
          if (invite.memberRole !== "OWNER") {
            if (!sub || sub.status !== "ACTIVE") {
              throw new ApiError("The organization subscription isn't active.", STATUS_CODES.CONFLICT);
            }
            if (invite.takesSeat && (await countSeatsInUse(tx, invite.orgId, invite.id)) >= sub.seatsPurchased) {
              throw new ApiError("No seats are available. Ask your admin.", STATUS_CODES.CONFLICT);
            }
          }

          const created = await tx.user.create({
            data: {
              firstName: data.firstName.trim(),
              lastName: data.lastName.trim(),
              email,
              password: hashed,
              authProvider: "LOCAL",
              // The emailed link proves the address.
              isVerified: true,
            },
          });

          const userRole = await tx.role.findUnique({ where: { name: "USER" } });
          if (!userRole) throw new ApiError("USER role not found", STATUS_CODES.SERVER_ERROR);
          await tx.userRole.create({ data: { userId: created.id, roleId: userRole.id } });

          await tx.userPreference.create({ data: { userId: created.id, enableFollowUpQuestions: true } });
          await tx.contextMemory.create({
            data: {
              userId: created.id,
              type: "GLOBAL",
              title: "My Name",
              memory: `My name is ${data.firstName.trim()} ${data.lastName.trim()}`,
              isAutoSelected: true,
              isAutoGenerated: true,
            },
          });

          const role = await tx.orgRole.findUniqueOrThrow({ where: { id: invite.orgRoleId } });
          await tx.orgMember.create({
            data: { orgId: invite.orgId, userId: created.id, memberRole: invite.memberRole, orgRoleId: role.id, takesSeat: invite.takesSeat },
          });

          if (!invite.takesSeat) {
            // Manage-only: an empty wallet, so existing wallet lookups still find one.
            await tx.userWallet.create({ data: { userId: created.id, tokensRemaining: 0, tokensUsed: 0 } });
          } else
          // Funds the seat only once billing is live; otherwise the activation step does it.
          await grantSeatQuota(tx, {
            userId: created.id,
            tokens: sub?.status === "ACTIVE" ? role.monthlyTokens : 0,
            videoCredits: sub?.status === "ACTIVE" ? role.monthlyVideoCredits : 0,
            reason: "ORG_SEAT_GRANT",
            meta: { orgId: invite.orgId },
          });

          await tx.orgInvite.update({ where: { id: invite.id }, data: { acceptedAt: new Date() } });
          await tx.orgAuditLog.create({
            data: {
              orgId: invite.orgId,
              actorUserId: created.id,
              action: "INVITE_ACCEPTED",
              targetType: "OrgInvite",
              targetId: String(invite.id),
              meta: { email },
            },
          });

          return created;
        },
        { isolationLevel: "Serializable" },
      );

      const secret = process.env.JWT_SECRET;
      if (!secret) throw new ApiError("JWT secret is not defined", STATUS_CODES.SERVER_ERROR);
      const jwtToken = jwt.sign({ id: user.id, role: "USER", timezone: user.timezone ?? "UTC" }, secret, {
        expiresIn: "90d",
      });
      return { token: jwtToken, userId: user.id };
    } catch (e: any) {
      if (e?.code === "P2002") throw new ApiError("This email already has an account.", STATUS_CODES.CONFLICT);
      throw e;
    }
  }
}

export default OrgInviteService;
